    def reverseList(self, head: ListNode | None) -> ListNode | None:
        '''prev = None
        curr = head
        while  curr:
            temp = curr.next
            curr.next = prev
            prev = curr
            curr = temp
        return prev'''
     
        if head is None or head.next is None:
            return head
        new_head = self.reverseList(head.next)
